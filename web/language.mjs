export function deviceLanguage(languages) {
  return languages.map(tag => tag.toLowerCase().split('-')[0]).find(lang => lang === 'cs' || lang === 'en') ?? 'en';
}

export function translate(language, message, values) {
  const text = language === 'en' && Object.hasOwn(english, message) ? english[message] : message;
  return values ? text.replace(/\{(\w+)\}/gu, (_, key) => values[key]) : text;
}
